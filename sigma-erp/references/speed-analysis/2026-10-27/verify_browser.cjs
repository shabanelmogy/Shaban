const { chromium } = require('C:/Users/user/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const fs=require('fs');const path=require('path');const {pathToFileURL}=require('url');
(async()=>{
 const root=__dirname;
 const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe'});
 const context=await browser.newContext({viewport:{width:1440,height:1050}});
 const page=await context.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await context.setOffline(true);
 await page.goto(pathToFileURL(path.join(root,'library/index.html')).href);
 const total=await page.locator('article').count();if(total!==311)throw new Error('Unexpected library count '+total);
 await page.screenshot({path:path.join(root,'qa/library.png')});
 await page.locator('#q').fill('deposit');
 const filtered=await page.locator('article').count();if(filtered<1||filtered>=total)throw new Error('Search filter failed');
 await page.locator('#q').fill('');await page.locator('#product').selectOption('vehicle-leasing-software');
 const leaseCount=await page.locator('article').count();if(leaseCount!==120)throw new Error('Product filter failed '+leaseCount);
 await page.goto(pathToFileURL(path.join(root,'Speed_Analysis_Guide.html')).href);
 const chapters=await page.locator('main > h2').count();if(chapters!==22)throw new Error('Chapter count '+chapters);
 await page.screenshot({path:path.join(root,'qa/guide-html.png')});
 await page.locator('nav a[href="#s5"]').click();if(!(await page.url()).endsWith('#s5'))throw new Error('Contents link failed');
 const manifest=JSON.parse(fs.readFileSync(path.join(root,'library/manifest.json'),'utf8'));
 const sample=manifest.find(r=>r.url==='https://speedautosystems.com/car-rental-software/user-guide/rental-agreement-opening/');
 await page.goto(pathToFileURL(path.join(root,'library',sample.local_path)).href);
 const images=await page.locator('img').evaluateAll(imgs=>imgs.map(i=>({src:i.src,ok:i.complete&&i.naturalWidth>0})));
 if(images.length<3||images.some(i=>!i.ok))throw new Error('Offline screenshots failed');
 await page.screenshot({path:path.join(root,'qa/sample-offline.png')});
 const result={total,filtered,leaseCount,chapters,offlineSampleImages:images.length,pageErrors:errors};
 if(errors.length)throw new Error(JSON.stringify(errors));
 fs.writeFileSync(path.join(root,'qa/browser-check.json'),JSON.stringify(result,null,2));console.log(result);
 await browser.close();
})().catch(e=>{console.error(e);process.exitCode=1});
