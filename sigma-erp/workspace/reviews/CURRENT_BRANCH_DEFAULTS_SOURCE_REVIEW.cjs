// Read-only source parsing/inventory. Does not build, typecheck, test, or run Sigma.
const fs = require('fs');
const path = require('path');
const cp = require('child_process');
const { pathToFileURL } = require('url');
const root = 'F:/My Work/Sigma/SiGmaAngularFrontEnd';
const ts = require(path.join(root, 'node_modules/typescript'));
function git(args) { return cp.execFileSync('git', ['-c', 'core.quotepath=false', '-c', 'core.safecrlf=false', '-C', root, ...args], { encoding: 'utf8' }); }
const changed = [...new Set((git(['diff', '--name-only']) + git(['ls-files', '--others', '--exclude-standard'])).trim().split(/\r?\n/))];
const issues = [];
const consumers = [];
const translationShapes = {};
let tsCount = 0;
function visit(node, fn) { fn(node); ts.forEachChild(node, child => visit(child, fn)); }
for (const relative of changed.filter(name => name.endsWith('.ts'))) {
  const file = path.join(root, relative);
  const source = fs.readFileSync(file, 'utf8');
  const ast = ts.createSourceFile(file, source, ts.ScriptTarget.Latest, true);
  tsCount++;
  for (const diagnostic of ast.parseDiagnostics) issues.push({ file: relative, message: ts.flattenDiagnosticMessageText(diagnostic.messageText, ' ') });
  visit(ast, node => {
    if (relative.endsWith('/vocabs/current-branch.ts') && ts.isVariableDeclaration(node) && ts.isObjectLiteralExpression(node.initializer)) {
      translationShapes[node.name.getText(ast)] = node.initializer.properties.map(property => property.name.getText(ast)).sort();
    }
    if (ts.isImportDeclaration(node) && ts.isStringLiteral(node.moduleSpecifier)) {
      const specifier = node.moduleSpecifier.text;
      if (specifier.includes('current-branch')) {
        const base = specifier.startsWith('src/') ? path.join(root, specifier) : path.resolve(path.dirname(file), specifier);
        if (!fs.existsSync(base + '.ts')) issues.push({ file: relative, message: 'Missing current-branch import: ' + specifier });
      }
    }
    if (ts.isClassDeclaration(node)) {
      const memberNames = new Set();
      let contextReady = false;
      for (const member of node.members) {
        const name = member.name && member.name.getText(ast);
        // Accessor pairs are legal.
        if (name && !ts.isGetAccessorDeclaration(member) && !ts.isSetAccessorDeclaration(member)) {
          if (memberNames.has(name)) issues.push({ file: relative, message: 'Duplicate class member: ' + name });
          memberNames.add(name);
        }
        if (name === 'currentBranch') contextReady = true;
        if (member.initializer && /this\.currentBranch\b/.test(member.initializer.getText(ast)) && !contextReady) {
          issues.push({ file: relative, message: 'currentBranch read before its field initializer' });
        }
      }
    }
  });
  if (source.includes('CurrentBranchService') && relative.includes('/modules/') && !relative.includes('/shared/service/current-branch.service.ts')) {
    const uses = source.split(/\r?\n/).map((line, index) => ({ line: index + 1, text: line.trim() }))
      .filter(item => /currentBranch\.(defaultBranchId|applyDefault|branch|filterBranchId)\(/.test(item.text));
    consumers.push({ file: relative, uses });
  }
}
(async () => {
  if (JSON.stringify(translationShapes.currentBranchEn) !== JSON.stringify(translationShapes.currentBranchAr)) {
    issues.push({ file: 'current-branch.ts', message: 'EN/AR vocabulary keys differ' });
  }
  const compiler = await import(pathToFileURL(path.join(root, 'node_modules/@angular/compiler/fesm2022/compiler.mjs')).href);
  let htmlCount = 0;
  for (const relative of changed.filter(name => name.endsWith('.html'))) {
    const parsed = compiler.parseTemplate(fs.readFileSync(path.join(root, relative), 'utf8'), relative);
    htmlCount++;
    for (const error of parsed.errors || []) issues.push({ file: relative, message: error.toString() });
  }
  const translationKeyCount = translationShapes.currentBranchEn?.length ?? 0;
  const report = { kind: 'Source syntax/import/order inventory only; no compilation/runtime claim', tsCount, htmlCount, translationKeyCount, consumerCount: consumers.length, issues, consumers };
  fs.writeFileSync('F:/My Work/Sigma/reviews/CURRENT_BRANCH_DEFAULTS_SOURCE_REVIEW.json', JSON.stringify(report, null, 2) + '\n');
  const consumerRows = consumers.map(consumer => `| \`${consumer.file}\` | ${consumer.uses.map(use => `L${use.line}: \`${use.text.replace(/\|/g, '&#124;')}\``).join('<br>')} |`).join('\n');
  fs.writeFileSync('F:/My Work/Sigma/reviews/CURRENT_BRANCH_DEFAULTS_CONSUMER_INVENTORY.md', '| Field | Value |\n|---|---|\n| Status | Implemented — source-only |\n| Owner verification pending | yes |\n\n# Branch-default source consumers\n\nGenerated by the read-only source inventory script from the scoped working diff; this is a usage inventory, not compiler or runtime evidence. Context/mode decisions and exclusions belong to the feature review.\n\n| File (frontend repository relative) | Exact consumer statements |\n|---|---|\n' + consumerRows + '\n');
  console.log(JSON.stringify({ tsCount, htmlCount, translationKeyCount, consumerCount: consumers.length, issues }, null, 2));
  process.exitCode = issues.length ? 1 : 0;
})().catch(error => { console.error(error.message); process.exitCode = 1; });
